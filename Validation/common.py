def _load_column_map() -> dict:
    if COLUMN_MAP_FILE.exists():
        with open(COLUMN_MAP_FILE, encoding="utf-8") as f:
            return {k: v for k, v in json.load(f).items() if v}
    return {}


def resolve_columns(df: pd.DataFrame, verbose: bool = True) -> dict[str, str | None]:
    """Returns {logical_key: actual_column_name or None}."""
    manual = _load_column_map()
    lower = {c.lower(): c for c in df.columns}
    out: dict[str, str | None] = {}
    for key, (cfg_attrs, cands) in COLUMN_CANDIDATES.items():
        found = None
        if key in manual and manual[key] in df.columns:
            found = manual[key]
        if found is None and config is not None:
            for a in cfg_attrs:
                v = getattr(config, a, None)
                if isinstance(v, str) and v in df.columns:
                    found = v
                    break
        if found is None:
            for c in cands:
                if c in df.columns:
                    found = c
                    break
                if c.lower() in lower:
                    found = lower[c.lower()]
                    break
        out[key] = found
    if verbose:
        missing = [k for k, v in out.items() if v is None]
        if missing:
            print(f"[warning] columns not found: {missing} "
                  f"(run 00_inspect_columns.py and edit column_map.json if needed)")
    return out


def topic_layer_columns(df: pd.DataFrame) -> list[str]:
    """Columns matching topic_cluster_<n>, sorted by n."""
    cols = [c for c in df.columns if re.fullmatch(r"topic_cluster_\d+", str(c))]
    return sorted(cols, key=lambda c: int(c.rsplit("_", 1)[1]))


