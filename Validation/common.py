class Report:
    """Accumulates text lines and a JSON dictionary; writes both at the end."""

    def __init__(self, name: str):
        self.name = name
        self.lines: list[str] = []
        self.data: dict = {}

    def h(self, title: str):
        self.p("")
        self.p("=" * 78)
        self.p(title)
        self.p("=" * 78)

    def p(self, *args):
        line = " ".join(str(a) for a in args)
        print(line)
        self.lines.append(line)

    def table(self, df: pd.DataFrame, max_rows: int = 200, floatfmt: str = "{:,.4f}"):
        with pd.option_context("display.max_rows", max_rows, "display.max_columns", 50,
                               "display.width", 200,
                               "display.float_format", lambda x: floatfmt.format(x)):
            self.p(df.to_string())

    def save(self):
        txt = OUT_DIR / f"{self.name}.txt"
        js = OUT_DIR / f"{self.name}.json"
        txt.write_text("\n".join(self.lines), encoding="utf-8")
        with open(js, "w", encoding="utf-8") as f:
            json.dump(self.data, f, ensure_ascii=False, indent=2, default=_json_default)
        print(f"\n>> Results written to:\n   {txt}\n   {js}")


def _json_default(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return None if np.isnan(o) else float(o)
    if isinstance(o, (np.ndarray,)):
        return o.tolist()
    if isinstance(o, pd.Timestamp):
        return o.isoformat()
    return str(o)


def save_csv(df: pd.DataFrame, name: str, index: bool = True):
    path = OUT_DIR / f"{name}.csv"
    df.to_csv(path, index=index, encoding="utf-8")
    print(f"   CSV: {path}")
    return path


def require(cols: dict, keys: list[str], script: str):
    missing = [k for k in keys if cols.get(k) is None]
    if missing:
        sys.exit(f"[ERROR] {script}: required columns not found: {missing}. "
                 f"Run 00_inspect_columns.py and populate column_map.json.")
