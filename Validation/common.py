def split_multi(value, sep_regex: str = r";\s*") -> list[str]:
    """Splits multi-valued WoS fields ('a; b; c'). Accepts lists/arrays."""
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return []
    if isinstance(value, (list, tuple, np.ndarray)):
        return [str(v).strip() for v in value if str(v).strip()]
    s = str(value).strip()
    if not s or s.lower() in {"nan", "none", "[]"}:
        return []
    if s.startswith("[") and s.endswith("]"):   # list stored as string: "['a', 'b']"
        try:
            import ast
            return [str(v).strip() for v in ast.literal_eval(s) if str(v).strip()]
        except (ValueError, SyntaxError):
            pass
    return [p.strip() for p in re.split(sep_regex, s) if p.strip()]


def is_filled(series: pd.Series) -> pd.Series:
    """True when the field has content (non-null, non-empty, not 'nan')."""
    def _f(v):
        if v is None:
            return False
        if isinstance(v, float) and np.isnan(v):
            return False
        if isinstance(v, (list, tuple, np.ndarray)):
            return len(v) > 0
        s = str(v).strip()
        return bool(s) and s.lower() not in {"nan", "none", "[]"}
    return series.map(_f)


def is_review(doc_type_series: pd.Series) -> pd.Series:
    """Document labeled as 'Review' (includes 'Review; Early Access')."""
    return doc_type_series.map(lambda v: any(t.lower() == "review" for t in split_multi(v)))


def exposure_years(year: pd.Series,
                   last_full_year: int = LAST_FULL_YEAR,
                   current_year_factor: float = CURRENT_YEAR_FACTOR) -> pd.Series:
    """Denominator from original code: (last_year - year + 1 + factor)."""
    return (last_full_year - year.astype(float) + 1 + current_year_factor)


